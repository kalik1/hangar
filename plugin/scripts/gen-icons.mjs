// gen-icons.mjs: write src/icons.generated.ts with every `mdi:<name>` icon the
// sources use, taken from @iconify/icons-mdi, so Headlamp renders them
// offline (it bundles only a few icons and fetches the rest from
// api.iconify.design, which an air-gapped cluster cannot reach).
// Runs before build and start; src/icons.test.ts checks the file is current.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const out = path.join(srcDir, 'icons.generated.ts');

export function usedIcons(dir = srcDir) {
  const used = new Set();
  const walk = d => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) walk(full);
      else if (/\.tsx?$/.test(e.name) && !e.name.includes('.test.') && e.name !== 'icons.generated.ts') {
        const text = fs.readFileSync(full, 'utf8');
        for (const m of text.matchAll(/mdi:([a-z0-9]+(?:-[a-z0-9]+)*)/g)) used.add(m[1]);
      }
    }
  };
  walk(dir);
  return [...used].sort();
}

export function render(names) {
  const icons = {};
  const missing = [];
  for (const name of names) {
    const file = path.join(root, 'node_modules/@iconify/icons-mdi', `${name}.js`);
    if (!fs.existsSync(file)) {
      missing.push(name);
      continue;
    }
    const text = fs.readFileSync(file, 'utf8');
    const m = text.match(/const data = (\{[\s\S]*?\});/);
    if (!m) {
      missing.push(name);
      continue;
    }
    // eslint-disable-next-line no-new-func
    icons[name] = Function(`return ${m[1]}`)();
  }
  if (missing.length) throw new Error(`unknown mdi icons: ${missing.join(', ')}`);
  return (
    '/* Generated by scripts/gen-icons.mjs from the mdi: names in src/. Do not edit. */\n' +
    "import type { IconifyIcon } from '@iconify/react';\n\n" +
    `export const ICONS: Record<string, IconifyIcon> = ${JSON.stringify(icons, null, 1)};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const names = usedIcons();
  const text = render(names);
  const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (prev !== text) fs.writeFileSync(out, text);
  console.log(`icons: ${names.length} mdi icons in src/icons.generated.ts`);
}
